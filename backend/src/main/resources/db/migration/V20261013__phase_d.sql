CREATE TABLE IF NOT EXISTS nhom_mon (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ten VARCHAR(50) NOT NULL UNIQUE,
 hien_thi BOOLEAN NOT NULL DEFAULT TRUE,
 thu_tu INTEGER NOT NULL DEFAULT 0
);
INSERT INTO nhom_mon(ten,thu_tu,hien_thi) VALUES ('Khoa học',0,TRUE),('Xã hội',1,TRUE),('Nghệ thuật',2,TRUE) ON CONFLICT (ten) DO NOTHING;
INSERT INTO nhom_mon(ten,thu_tu,hien_thi)
 SELECT DISTINCT trim(danh_muc),3,TRUE FROM chu_de
 WHERE danh_muc IS NOT NULL AND trim(danh_muc) <> '' AND lower(trim(danh_muc)) <> lower('Tất cả')
 ON CONFLICT (ten) DO NOTHING;
ALTER TABLE chu_de ADD COLUMN IF NOT EXISTS nhom_mon_id BIGINT REFERENCES nhom_mon(id);
ALTER TABLE chu_de ADD COLUMN IF NOT EXISTS hien_dap_an_sau_nop BOOLEAN DEFAULT TRUE;
ALTER TABLE chu_de ADD COLUMN IF NOT EXISTS xao_tron_cau_hoi BOOLEAN DEFAULT FALSE;
ALTER TABLE chu_de ADD COLUMN IF NOT EXISTS xao_tron_lua_chon BOOLEAN DEFAULT FALSE;
UPDATE chu_de SET nhom_mon_id = (SELECT id FROM nhom_mon WHERE ten = trim(chu_de.danh_muc)) WHERE nhom_mon_id IS NULL;
UPDATE chu_de SET nhom_mon_id = (SELECT id FROM nhom_mon WHERE ten = 'Khoa học'), danh_muc = 'Khoa học' WHERE nhom_mon_id IS NULL;
UPDATE chu_de SET hien_dap_an_sau_nop = TRUE WHERE hien_dap_an_sau_nop IS NULL;
